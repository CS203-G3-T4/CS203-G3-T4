-- F1 (CSDT4-25/72): periods when the NEMS feed failed or served stale data.
-- An incident opens on the first FAILURE or STALE_SOURCE poll and closes (ended_at)
-- on the next SUCCESS poll. Open incidents have ended_at NULL; at most one is open.
CREATE TABLE feed_incident (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    reason VARCHAR(1000) NOT NULL,
    failed_polls INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT ck_feed_incident_period CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_feed_incident_failed_polls CHECK (failed_polls >= 1)
);

CREATE UNIQUE INDEX ux_feed_incident_one_open
    ON feed_incident ((ended_at IS NULL))
    WHERE ended_at IS NULL;

CREATE INDEX idx_feed_incident_started_at
    ON feed_incident (started_at DESC, id DESC);
