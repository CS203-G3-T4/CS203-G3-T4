-- CSDT4-41: the charges on a household bill besides the wholesale energy price, for the
-- month-to-date spend. Each row records where its rate comes from.
--
-- unit:  SGD_PER_KWH   added to every kWh (rates here exclude GST)
--        SGD_PER_MONTH a fixed monthly charge, counted in proportion to how much of the month has passed
--        PERCENT       a tax on the subtotal (GST)
-- applies_from/applies_to: Singapore time-of-day window (may cross midnight); NULL means all day.
-- effective_from/effective_to: the dates the rate applies (effective_to NULL = until replaced).
CREATE TABLE tariff_component (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_type VARCHAR(20) NOT NULL CHECK (plan_type IN ('PRICE_LINKED')),
    code VARCHAR(40) NOT NULL,
    charge VARCHAR(120) NOT NULL,
    unit VARCHAR(20) NOT NULL CHECK (unit IN ('SGD_PER_KWH', 'SGD_PER_MONTH', 'PERCENT')),
    rate NUMERIC(12, 6) NOT NULL CHECK (rate >= 0),
    applies_from TIME,
    applies_to TIME,
    effective_from DATE NOT NULL,
    effective_to DATE,
    source VARCHAR(300) NOT NULL,
    source_url VARCHAR(500),
    CONSTRAINT ck_tariff_component_window CHECK ((applies_from IS NULL) = (applies_to IS NULL)),
    CONSTRAINT ck_tariff_component_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT uq_tariff_component UNIQUE (plan_type, code, effective_from)
);

