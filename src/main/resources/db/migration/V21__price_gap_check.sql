-- F1 (CSDT4-27/77): result of each check for half-hours missing from market_price.
-- missing_intervals holds the interval_start of every missing half-hour in
-- [window_start, window_end); an empty array means the window was complete.
CREATE TABLE price_gap_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checked_at TIMESTAMPTZ NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    missing_intervals TIMESTAMPTZ[] NOT NULL,
    CONSTRAINT ck_price_gap_check_window CHECK (window_end >= window_start)
);

CREATE INDEX idx_price_gap_check_checked_at
    ON price_gap_check (checked_at DESC, id DESC);
