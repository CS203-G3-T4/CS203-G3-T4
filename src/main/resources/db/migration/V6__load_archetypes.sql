ALTER TABLE household
    ADD CONSTRAINT fk_household_archetype
    FOREIGN KEY (archetype_id) REFERENCES load_archetype (id);

-- Give existing households the archetype that matches their home type.
UPDATE household h
SET archetype_id = a.id
FROM load_archetype a
WHERE a.dwelling_type = h.dwelling_type
  AND h.archetype_id IS NULL;
