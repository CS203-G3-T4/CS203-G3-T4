-- F2 (CSDT4-29): household load archetypes calibrated to EMA's published averages.
-- monthly_kwh = average monthly household electricity consumption in 2024, by dwelling type,
-- from MSE's written reply to a parliamentary question (24 Sep 2025), which cites EMA data.
-- These are MODELLED figures, not metered data. The daily shape lives in DailyLoadShape.java.

CREATE TABLE load_archetype (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    dwelling_type VARCHAR(40) NOT NULL UNIQUE,
    label VARCHAR(80) NOT NULL,
    monthly_kwh NUMERIC(8, 1) NOT NULL CHECK (monthly_kwh > 0),
    -- A weekend day uses this many times the energy of a weekday (assumption, not EMA data).
    weekend_factor NUMERIC(4, 2) NOT NULL DEFAULT 1.10 CHECK (weekend_factor > 0),
    source VARCHAR(300) NOT NULL
);

